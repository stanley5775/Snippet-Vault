import { resolveTemplate } from '@/lib/templates/items';
import { slugify } from '@/lib/templates/paths';
import type { Asset, StarterTemplate } from '@/types';

export interface ZipFile {
  path: string;
  content: string;
}

export interface ZipPlan {
  filename: string;
  files: ZipFile[];
  /** Paths of deleted snippets that could not be included. */
  skipped: string[];
  readmeIncluded: boolean;
}

export type ZipResult = { ok: true; plan: ZipPlan } | { ok: false; reason: string };

const code = (text: string) => `\`${text.replaceAll('`', "'")}\``;

export function buildReadme(
  template: Pick<StarterTemplate, 'name' | 'description'>,
  files: ZipFile[],
  skipped: string[],
  date: string,
): string {
  const lines = [`# ${template.name}`, ''];
  if (template.description) lines.push(template.description, '');
  lines.push(`Generated by Snippet Vault on ${date}.`, '', '## Files', '');
  for (const file of files) lines.push(`- ${code(file.path)}`);
  if (skipped.length > 0) {
    lines.push(
      '',
      '## Skipped',
      '',
      'These snippets had been deleted when this starter was generated:',
      '',
    );
    for (const path of skipped) lines.push(`- ${code(path)}`);
  }
  lines.push('');
  return lines.join('\n');
}

export function planZip(
  template: StarterTemplate,
  assets: Record<string, Asset>,
  options: { readme: boolean; now: Date },
): ZipResult {
  const resolved = resolveTemplate(template, assets);

  const badPaths = resolved.filter((r) => r.pathError).length;
  if (badPaths > 0) {
    return {
      ok: false,
      reason: `Fix ${badPaths} file ${badPaths === 1 ? 'path' : 'paths'} before downloading.`,
    };
  }

  const files: ZipFile[] = [];
  const skipped: string[] = [];
  for (const r of resolved) {
    if (r.content === undefined) skipped.push(r.item.path);
    else files.push({ path: r.item.path, content: r.content });
  }
  if (files.length === 0)
    return { ok: false, reason: 'There are no files to download yet.' };

  let readmeIncluded = false;
  if (options.readme) {
    const taken = new Set(files.map((f) => f.path.toLowerCase()));
    // Never overwrite a file the user placed themselves
    const readmePath = taken.has('readme.md') ? 'README.snippet-vault.md' : 'README.md';
    if (!taken.has(readmePath.toLowerCase())) {
      const date = options.now.toISOString().slice(0, 10);
      files.push({
        path: readmePath,
        content: buildReadme(template, files, skipped, date),
      });
      readmeIncluded = true;
    }
  }

  return {
    ok: true,
    plan: { filename: `${slugify(template.name)}.zip`, files, skipped, readmeIncluded },
  };
}

/** fflate loads only when someone actually downloads a ZIP. */
export async function zipBytes(plan: ZipPlan): Promise<Uint8Array> {
  const { strToU8, zipSync } = await import('fflate');
  const entries: Record<string, Uint8Array> = {};
  for (const file of plan.files) entries[file.path] = strToU8(file.content);
  return zipSync(entries);
}
